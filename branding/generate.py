"""Builds OAmp's icon files from the shapes defined here.

Run from the repo root: python3 branding/generate.py
Needs Pillow and CairoSVG (pip install pillow cairosvg).
Writes the SVG sources in branding/, the Windows .ico, the Android
launcher PNGs, the adaptive icon vectors and the notification icon.
"""
import io, os
from PIL import Image

CORAL = "#FF6B4A"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android/app/src/main/res")

# Main mark, 1024 units: a coral ring with a seven-bar sound wave inside.
RING_R, RING_W = 300, 104
BARS = [120, 220, 330, 400, 300, 200, 110]  # heights, centred on the ring
BAR_STEP, BAR_W = 62, 40
# Small mark, 24 units, for 32 px and below: thicker strokes, five bars.
S_RING_R, S_RING_W = 9.6, 2.6
S_BARS = [4, 7.5, 11, 7.5, 4]
S_BAR_STEP, S_BAR_W = 3.1, 1.7

BG_TOP, BG_BOTTOM, BG_SOLID = "#232327", "#0B0B0C", "#161618"


def bg(size, radius):
    return (f'<defs><linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">'
            f'<stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/>'
            f'</linearGradient></defs><rect width="{size}" height="{size}" rx="{radius}" fill="url(#bg)"/>')


def mark(c, r, w, bars, step, bw, ring, bar):
    s = f'<circle cx="{c}" cy="{c}" r="{r}" fill="none" stroke="{ring}" stroke-width="{w}"/>'
    n = len(bars)
    for i, h in enumerate(bars):
        x = c + (i - (n - 1) / 2) * step
        s += (f'<rect x="{x - bw / 2:g}" y="{c - h / 2:g}" width="{bw:g}" height="{h:g}" '
              f'rx="{bw / 2:g}" fill="{bar}"/>')
    return s


def svg(size, body):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">{body}</svg>'


ICON = svg(1024, bg(1024, 228) + mark(512, RING_R, RING_W, BARS, BAR_STEP, BAR_W, CORAL, "#FFFFFF"))
ICON_SMALL = svg(24, bg(24, 5.4) + mark(12, S_RING_R, S_RING_W, S_BARS, S_BAR_STEP, S_BAR_W, CORAL, "#FFFFFF"))
MONO = svg(24, mark(12, S_RING_R, S_RING_W, S_BARS, S_BAR_STEP, S_BAR_W, "#FFFFFF", "#FFFFFF"))


def render(sources):
    """Renders {name: (svg, px)} to PIL images."""
    import cairosvg
    return {name: Image.open(io.BytesIO(cairosvg.svg2png(bytestring=src.encode(),
                                                         output_width=px, output_height=px))).convert("RGBA")
            for name, (src, px) in sources.items()}


def vector_mark(c, scale, ring, bar):
    """Android vector paths for the main mark, centred on c, 1024 units -> dp."""
    r, w = RING_R * scale, RING_W * scale
    p = (f'    <path android:strokeColor="{ring}" android:strokeWidth="{w:.3f}" android:fillColor="#00000000"\n'
         f'        android:pathData="M{c:g},{c - r:.3f}a{r:.3f},{r:.3f} 0,1 1,0 {2 * r:.3f}'
         f'a{r:.3f},{r:.3f} 0,1 1,0 {-2 * r:.3f}z"/>\n')
    n, bw = len(BARS), BAR_W * scale
    for i, h in enumerate(BARS):
        x = c + (i - (n - 1) / 2) * BAR_STEP * scale
        half = h * scale / 2 - bw / 2
        p += (f'    <path android:strokeColor="{bar}" android:strokeWidth="{bw:.3f}" android:strokeLineCap="round"\n'
              f'        android:pathData="M{x:.3f},{c - half:.3f}V{c + half:.3f}"/>\n')
    return p


def vector(size, body, extra=""):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'{extra}<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp" android:height="{size}dp"\n'
            f'    android:viewportWidth="{size}" android:viewportHeight="{size}">\n{body}</vector>\n')


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main():
    here = os.path.join(ROOT, "branding")
    write(os.path.join(here, "oamp-icon.svg"), ICON + "\n")
    write(os.path.join(here, "oamp-icon-small.svg"), ICON_SMALL + "\n")
    write(os.path.join(here, "oamp-glyph.svg"), MONO + "\n")

    ico_sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
    launcher = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    jobs = {f"ico{s}": (ICON_SMALL if s <= 32 else ICON, s) for s in ico_sizes}
    jobs.update({f"m{d}": (ICON, s) for d, s in launcher.items()})
    imgs = render(jobs)

    frames = [imgs[f"ico{s}"] for s in ico_sizes]
    frames[-1].save(os.path.join(ROOT, "windows/runner/resources/app_icon.ico"),
                    sizes=[(s, s) for s in ico_sizes], append_images=frames[:-1])
    for d in launcher:
        imgs[f"m{d}"].save(os.path.join(RES, f"mipmap-{d}/ic_launcher.png"), optimize=True)

    # Adaptive icon (Android 8+): the ring fills about 58 of the 66 dp safe zone.
    scale = 58 / (2 * (RING_R + RING_W / 2))
    note = ("<!-- Generated by branding/generate.py; edit the script, not this file. -->\n")
    write(os.path.join(RES, "drawable/ic_launcher_foreground.xml"),
          vector(108, vector_mark(54, scale, CORAL, "#FFFFFFFF"), note))
    write(os.path.join(RES, "drawable/ic_launcher_monochrome.xml"),
          vector(108, vector_mark(54, scale, "#FFFFFFFF", "#FFFFFFFF"), note))
    write(os.path.join(RES, "values/ic_launcher_colors.xml"),
          '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          f'    <color name="ic_launcher_background">{BG_SOLID}</color>\n</resources>\n')
    write(os.path.join(RES, "mipmap-anydpi-v26/ic_launcher.xml"),
          '<?xml version="1.0" encoding="utf-8"?>\n'
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@color/ic_launcher_background"/>\n'
          '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
          '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
          '</adaptive-icon>\n')

    # Status bar icon: Android uses only the alpha channel, so it is all white.
    body = (f'    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{S_RING_W}" android:fillColor="#00000000"\n'
            f'        android:pathData="M12,{12 - S_RING_R:g}a{S_RING_R},{S_RING_R} 0,1 1,0 {2 * S_RING_R:g}'
            f'a{S_RING_R},{S_RING_R} 0,1 1,0 {-2 * S_RING_R:g}z"/>\n')
    for i, h in enumerate(S_BARS):
        x = 12 + (i - 2) * S_BAR_STEP
        half = h / 2 - S_BAR_W / 2
        body += (f'    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="{S_BAR_W}" android:strokeLineCap="round"\n'
                 f'        android:pathData="M{x:.2f},{12 - half:.2f}V{12 + half:.2f}"/>\n')
    write(os.path.join(RES, "drawable/ic_stat_oamp.xml"), vector(24, body,
          "<!-- Status bar icon for the playback notification: OAmp's ring mark in white.\n"
          "     Android draws status bar icons from the alpha channel only.\n"
          "     Generated by branding/generate.py; edit the script, not this file. -->\n"))


if __name__ == "__main__":
    main()
